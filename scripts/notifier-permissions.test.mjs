// notifier プラグインのコマンドが、Kotlin・build.rs・既定の権限（default.toml）で食い違わないことを確かめる。
// 権限に無いコマンドは、実行時に「not allowed by ACL」で拒否される（Android の最近の画像で実際に起きた）
import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = join(dirname(fileURLToPath(import.meta.url)), '..', 'app', 'src-tauri', 'plugins', 'notifier');
const read = (p) => readFileSync(join(dir, p), 'utf8');

const snake = (name) => name.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);

const buildCommands = [...read('build.rs').match(/COMMANDS: &\[&str\] = &\[([\s\S]*?)\];/)[1].matchAll(/"([a-z_]+)"/g)].map((m) => m[1]);
const kotlinCommands = [...read('android/src/main/java/NotifierPlugin.kt').matchAll(/@Command\s+fun (\w+)/g)].map((m) => snake(m[1]));
const allowed = new Set([...read('permissions/default.toml').matchAll(/"allow-([a-z-]+)"/g)].map((m) => m[1].replaceAll('-', '_')));

test('Kotlin の @Command は、すべて build.rs の COMMANDS にある', () => {
  assert.ok(kotlinCommands.length > 0);
  for (const c of kotlinCommands) assert.ok(buildCommands.includes(c), `build.rs の COMMANDS に ${c} が無い`);
});

test('Kotlin の @Command は、すべて default.toml で許可されている', () => {
  for (const c of kotlinCommands) assert.ok(allowed.has(c), `default.toml に allow-${c.replaceAll('_', '-')} が無い`);
});

test('許可の定義ファイルが、COMMANDS のすべてにある', () => {
  for (const c of buildCommands) read(`permissions/autogenerated/commands/${c}.toml`);
});
