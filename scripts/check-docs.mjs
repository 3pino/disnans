#!/usr/bin/env node
// markdown の検査（依存なし）。使い方: node scripts/check-docs.mjs
//
// (1) git 管理の *.md の相対リンクが、存在するファイル（ディレクトリ）を指す（エラー）
// (2) `#アンカー` が、リンク先の md の見出しにある（GitHub 方式のスラッグ。エラー）
// (3) docs/README.md（目次）に載っていない docs/ の md（警告）。docs/README.md が無いときは何もしない
// (4) 「端末」という語が docs/ と README.md にある（警告）
// (5) 終了コード: (1)(2) の違反があれば 1。警告だけなら 0
//
// コードブロック（``` / ~~~）の中と、インラインのコード（`...`）の中は見ない。
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, statSync } from 'node:fs';
import { posix, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const INDEX = 'docs/README.md';
export const TERM = '端末';

/** 自動生成のファイルと依存のフォルダは対象外 */
export function selectFiles(paths) {
  return paths.filter(
    (p) =>
      p.endsWith('.md') &&
      !p.includes('node_modules/') &&
      !/(^|\/)autogenerated\/reference\.md$/.test(p),
  );
}

/**
 * GitHub の見出しのスラッグ（github-slugger と同じ考え方）。
 * 小文字にし、letters・数字・結合記号・`_`・`-` 以外（記号・全角の句読点・絵文字）を消し、空白を `-` にする。
 * 日本語の文字はそのまま残る。
 */
export function slugify(text) {
  // trim はしない（記号を消したあとに残る空白も `-` になる。GitHub の絵文字の見出しは先頭が `-` になる）
  return text
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\p{M}_\- ]/gu, '')
    .replace(/ /g, '-');
}

/** 見出しの文字（リンク・コード・強調の記号を外した、表示に近い文字） */
export function plainText(raw) {
  return raw
    .replace(/!\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/<[^>]+>/g, '')
    .replace(/[`*~]/g, '')
    .trim();
}

/** 行ごとに、コードブロックの外かどうかを返す（フェンスの行自体は外側とみなす） */
function outsideFences(lines) {
  const out = [];
  let fence = null;
  for (const line of lines) {
    const m = /^\s*(`{3,}|~{3,})/.exec(line);
    if (fence) {
      out.push(false);
      if (m && m[1][0] === fence[0] && m[1].length >= fence.length && line.trim() === m[1]) fence = null;
    } else if (m) {
      fence = m[1];
      out.push(false);
    } else {
      out.push(true);
    }
  }
  return out;
}

/** 見出し（コードブロックの中は除く）。同じスラッグは -1, -2 … を付ける */
export function headings(text) {
  const lines = text.split('\n');
  const inside = outsideFences(lines);
  const seen = new Map();
  const result = [];
  lines.forEach((line, i) => {
    if (!inside[i]) return;
    const m = /^ {0,3}(#{1,6})[ \t]+(.+?)(?:[ \t]+#+)?[ \t]*$/.exec(line);
    if (!m) return;
    const base = slugify(plainText(m[2]));
    if (!base) return;
    const n = seen.get(base) ?? 0;
    seen.set(base, n + 1);
    result.push({ line: i + 1, level: m[1].length, text: plainText(m[2]), slug: n === 0 ? base : `${base}-${n}` });
  });
  return result;
}

/** リンク（`[..](target)` と `![..](target)`）。コードの中は除く */
export function links(text) {
  const lines = text.split('\n');
  const inside = outsideFences(lines);
  const result = [];
  lines.forEach((line, i) => {
    if (!inside[i]) return;
    // インラインのコードは同じ長さの空白にして、位置を保ったまま外す
    const masked = line.replace(/(`+)[^`]*?\1/g, (s) => ' '.repeat(s.length));
    const re = /!?\[[^\]]*\]\(\s*<?([^)\s>]*)>?(?:\s+"[^"]*")?\s*\)/g;
    let m;
    while ((m = re.exec(masked)) !== null) {
      result.push({ line: i + 1, target: m[1] });
    }
  });
  return result;
}

/** 外部のリンク（http:・mailto: など）は見ない */
function isExternal(target) {
  return /^[a-z][a-z0-9+.-]*:/i.test(target) || target.startsWith('//');
}

function safeDecode(s) {
  try {
    return decodeURIComponent(s);
  } catch {
    return s;
  }
}

/**
 * 文書の検査。files は git 管理の md の相対パス（POSIX）。readFile(rel) は中身を返す。exists(rel) は存在を返す。
 * 返り値: { checked, errors: [{file, line, message}], warnings: [{file, line, message}] }
 */
export function checkDocs({ files, readFile, exists, isDir }) {
  const errors = [];
  const warnings = [];
  const cache = new Map();
  const load = (rel) => {
    if (!cache.has(rel)) cache.set(rel, readFile(rel));
    return cache.get(rel);
  };
  const anchorsOf = (rel) => new Set(headings(load(rel)).map((h) => h.slug));

  /** リンク先の相対パス（リポジトリのルートからの POSIX パス）を作る */
  const resolveTarget = (from, pathPart) =>
    posix.normalize(posix.join(posix.dirname(from), safeDecode(pathPart))).replace(/\/+$/, '');

  for (const file of files) {
    for (const { line, target } of links(load(file))) {
      if (!target || isExternal(target)) continue;
      const hash = target.indexOf('#');
      const pathPart = hash === -1 ? target : target.slice(0, hash);
      const anchor = hash === -1 ? null : safeDecode(target.slice(hash + 1));
      const dest = pathPart === '' ? file : resolveTarget(file, pathPart);
      if (dest.startsWith('../')) {
        errors.push({ file, line, message: `リンク先がリポジトリの外です: ${target}` });
        continue;
      }
      if (pathPart !== '' && !exists(dest)) {
        errors.push({ file, line, message: `リンク先のファイルがありません: ${target}` });
        continue;
      }
      if (anchor && anchor !== '' && dest.endsWith('.md') && !isDir(dest)) {
        if (!anchorsOf(dest).has(anchor)) {
          errors.push({ file, line, message: `リンク先の見出しがありません: #${anchor}（${dest}）` });
        }
      }
    }
  }

  // (3) 目次に載っていない docs/ の md
  if (exists(INDEX)) {
    const listed = new Set();
    for (const { target } of links(load(INDEX))) {
      if (!target || isExternal(target)) continue;
      const hash = target.indexOf('#');
      const pathPart = hash === -1 ? target : target.slice(0, hash);
      if (pathPart) listed.add(resolveTarget(INDEX, pathPart));
    }
    for (const file of files) {
      if (file.startsWith('docs/') && file !== INDEX && !listed.has(file)) {
        warnings.push({ file, line: 1, message: `${INDEX} の目次に載っていません` });
      }
    }
  }

  // (4) 用語
  for (const file of files) {
    if (!(file === 'README.md' || file.startsWith('docs/'))) continue;
    load(file).split('\n').forEach((line, i) => {
      if (line.includes(TERM)) {
        warnings.push({ file, line: i + 1, message: `「${TERM}」という語があります（確認してください）` });
      }
    });
  }

  const order = (a, b) => a.file.localeCompare(b.file) || a.line - b.line;
  errors.sort(order);
  warnings.sort(order);
  return { checked: files.length, errors, warnings };
}

/**
 * ファイルの読み書きつきの実行（リポジトリのルートを基準にする）。
 * 対象は git が管理している md と、まだ追加していない新しい md（除外規則の外のもの）。
 * 作業ツリーから消えたもの（削除の途中）は対象にしない。
 */
export function runOnRepo(root) {
  const listed = execFileSync('git', ['ls-files', '--cached', '--others', '--exclude-standard', '--', '*.md'], {
    cwd: root,
    encoding: 'utf8',
  })
    .split('\n')
    .filter(Boolean);
  const abs = (rel) => `${root}/${rel}`;
  const files = selectFiles([...new Set(listed)]).filter((rel) => existsSync(abs(rel)));
  return checkDocs({
    files,
    readFile: (rel) => readFileSync(abs(rel), 'utf8'),
    exists: (rel) => existsSync(abs(rel)),
    isDir: (rel) => existsSync(abs(rel)) && statSync(abs(rel)).isDirectory(),
  });
}

/** 終了コード: (1)(2) のエラーがあれば 1。警告だけなら 0 */
export function exitCode(result) {
  return result.errors.length > 0 ? 1 : 0;
}

export function formatReport(result) {
  const lines = [];
  for (const e of result.errors) lines.push(`${e.file}:${e.line}: ${e.message}`);
  for (const w of result.warnings) lines.push(`${w.file}:${w.line}: 警告: ${w.message}`);
  lines.push(
    `検査: ${result.checked} 件の md、エラー ${result.errors.length} 件、警告 ${result.warnings.length} 件`,
  );
  return lines.join('\n');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
  const result = runOnRepo(root);
  console.log(formatReport(result));
  process.exitCode = exitCode(result);
}
