// Android の Tauri プラグイン（notifier・screen・system-bars・apk-updater）の ACL を確かめる。
// 権限に無いコマンドは実行時に「not allowed by ACL」で拒否されるので、次の三つが食い違わないことを見る:
// build.rs の COMMANDS、Kotlin の @Command、default.toml の allow、そして TypeScript からの呼び出し。
import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, readdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'app');
const plugins = join(root, 'src-tauri', 'plugins');
const srcDir = join(root, 'src');

const snake = (name) => name.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);
// .tauri は Tauri の API のコピー（ビルドの生成物）なので読まない
const readAll = (dir) =>
  readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.name !== '.tauri' && e.name !== 'build')
    .flatMap((e) => {
      const p = join(dir, e.name);
      return e.isDirectory() ? readAll(p) : [p];
    });

// Tauri の Plugin 基底クラスが持つ（各プラグインの Kotlin には無い）
const inherited = new Set(['register_listener', 'remove_listener']);

const info = {};
for (const name of readdirSync(plugins)) {
  const dir = join(plugins, name);
  const build = readFileSync(join(dir, 'build.rs'), 'utf8');
  const commands = [...build.match(/COMMANDS: &\[&str\] = &\[([\s\S]*?)\];/)[1].matchAll(/"([a-z_]+)"/g)].map((m) => m[1]);
  const kotlin = readAll(join(dir, 'android'))
    .filter((p) => p.endsWith('.kt'))
    .flatMap((p) => [...readFileSync(p, 'utf8').matchAll(/@Command\s+fun (\w+)/g)].map((m) => snake(m[1])));
  const allowed = new Set([...readFileSync(join(dir, 'permissions', 'default.toml'), 'utf8').matchAll(/"allow-([a-z-]+)"/g)].map((m) => m[1].replaceAll('-', '_')));
  info[name] = { commands, kotlin, allowed };
}

// TypeScript の呼び出し（プラグイン名 → コマンド）。テンプレートで組む呼び出しは、その中の関数名で見る
const tsCalls = {};
const addCall = (plugin, cmd, where) => {
  (tsCalls[plugin] ??= []).push({ cmd, where });
};
for (const file of readAll(srcDir).filter((p) => /\.(ts|svelte)$/.test(p) && !/\.test\.ts$/.test(p))) {
  const text = readFileSync(file, 'utf8');
  const where = file.slice(srcDir.length);
  for (const m of text.matchAll(/plugin:([a-z-]+)\|([a-z_]+)/g)) addCall(m[1], m[2], where);
  for (const m of text.matchAll(/invokeNotifier(?:<[^>]*>)?\(\s*'([a-z_]+)'/g)) addCall('notifier', m[1], where);
  for (const m of text.matchAll(/invokeScreen(?:<[^>]*>)?\(\s*'([a-z_]+)'/g)) addCall('screen', m[1], where);
  if (where.endsWith('call/nativeCall.ts')) {
    for (const m of text.matchAll(/\bcall\('([a-z_]+)'/g)) addCall('notifier', m[1], where);
  }
  if (where.endsWith('call/nativePort.ts')) {
    for (const m of text.matchAll(/\binvoke(?:<[^>]*>)?\(\s*'(native_call_[a-z_]+)'/g)) addCall('notifier', m[1], where);
  }
}

test('各プラグインの COMMANDS は、Kotlin の @Command にあり、default.toml で許可されている', () => {
  for (const [name, p] of Object.entries(info)) {
    assert.ok(p.commands.length > 0, name);
    for (const c of p.commands) {
      assert.ok(inherited.has(c) || p.kotlin.includes(c), `${name}: Kotlin に ${c} が無い`);
      assert.ok(p.allowed.has(c), `${name}: default.toml に allow-${c.replaceAll('_', '-')} が無い`);
    }
  }
});

test('各プラグインの COMMANDS には、許可の定義ファイルがある', () => {
  for (const [name, p] of Object.entries(info)) {
    for (const c of p.commands) {
      readFileSync(join(plugins, name, 'permissions', 'autogenerated', 'commands', `${c}.toml`), 'utf8');
    }
  }
});

test('TypeScript から呼ぶコマンドは、すべて COMMANDS と default.toml の許可にある', () => {
  // 画面の操作は `${operation}_capture` で組むので、その三つを明示する
  const screenBuilt = ['start_capture', 'update_capture', 'stop_capture'];
  assert.ok(readFileSync(join(srcDir, 'lib', 'plugins', 'nativeScreen.ts'), 'utf8').includes('_capture`'));
  for (const [plugin, calls] of Object.entries(tsCalls)) {
    const p = info[plugin];
    assert.ok(p, `プラグイン ${plugin} が無い`);
    const names = plugin === 'screen' ? [...calls.map((c) => c.cmd), ...screenBuilt] : calls.map((c) => c.cmd);
    for (const cmd of names) {
      assert.ok(p.commands.includes(cmd), `${plugin}: TypeScript の ${cmd}（${calls.find((c) => c.cmd === cmd)?.where ?? 'nativeScreen.ts'}）が COMMANDS に無い`);
      assert.ok(p.allowed.has(cmd), `${plugin}: default.toml に allow-${cmd.replaceAll('_', '-')} が無い`);
    }
  }
});
